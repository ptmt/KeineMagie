"""Actual Chromium playback of cached paid WAV, injected by test-only Go fixture.
No provider credentials or paid calls. Source must match the recorded acceptance.
"""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
root = Path(os.environ.get('DICTATION_FIXTURE_DIR', '/Users/tinyserve/.hermes/cache/scratch/diktat-fixture'))
info = json.loads((root/'fixture.json').read_text())
evidence = Path('/Users/tinyserve/.hermes/cache/scratch/diktat-cached-browser')
evidence.mkdir(exist_ok=True)
source = 'Heute scheint die Sonne.'
with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width':1280,'height':950})
    context.add_cookies([{'name':'__Host-km-session','value':info['browser'],'domain':'localhost','path':'/','secure':True,'httpOnly':True,'sameSite':'Strict'}])
    page = context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(info['url']+'/#dictation')
    page.get_by_role('button',name='Add text',exact=True).click()
    page.get_by_role('textbox',name='Title',exact=True).fill('Cached accepted OpenAI WAV')
    page.get_by_role('textbox',name='Original text',exact=True).fill(source)
    page.get_by_role('button',name='Save text',exact=True).click()
    prepare=page.get_by_role('button',name='Prepare audio',exact=True)
    prepare.wait_for()
    assert source not in page.locator('#dictation').inner_text()
    prepare.click()
    play=page.locator('.dictation-player > button').first
    expect(play).to_be_enabled(timeout=10000)
    expect(page.locator('.dictation-disclosure summary')).to_have_accessible_name('Audio details')
    play.click()
    page.wait_for_function("() => document.querySelector('#dictation').textContent.includes('1 completed readings')",timeout=15000)
    page.screenshot(path=str(evidence/'whole-ended.png'),full_page=True)
    play.click()
    page.get_by_role('button',name='Pause',exact=True).click()
    play.click()
    page.wait_for_function("() => document.querySelector('#dictation').textContent.includes('2 completed readings')",timeout=15000)
    page.get_by_role('button',name='By sentences',exact=True).click()
    page.get_by_role('button',name='Next',exact=True).click()
    expect(play).to_be_enabled(timeout=10000)
    play.click()
    page.wait_for_timeout(2300)
    draft=page.get_by_role('textbox',name='What you heard')
    draft.fill(source)
    page.wait_for_timeout(1200)
    page.reload()
    page.get_by_role('button',name='Cached accepted OpenAI WAV · In progress',exact=True).first.click()
    expect(draft).to_have_value(source)
    page.get_by_role('button',name='Check',exact=True).click()
    expect(page.locator('.dictation-original')).to_have_count(0)
    page.get_by_role('button',name='Show original',exact=True).click()
    expect(page.locator('.dictation-original')).to_have_text(source)
    page.screenshot(path=str(evidence/'checked.png'),full_page=True)
    page.get_by_role('button',name='New attempt',exact=True).click()
    expect(page.get_by_role('button',name='Check',exact=True)).to_be_visible()
    assert source not in page.locator('#dictation').inner_text()
    page.get_by_role('textbox',name='What you heard').fill('second attempt')
    page.wait_for_timeout(1200)
    page.once('dialog',lambda dialog:dialog.accept())
    page.locator('.dictation-attempt-menu summary').click()
    page.get_by_role('button',name='Delete attempt',exact=True).click()
    expect(page.get_by_role('button',name='Add text',exact=True)).to_be_visible()
    assert not errors, errors
    (evidence/'result.json').write_text(json.dumps({'transport':'test-only cached real OpenAI WAV, no generation','checks':['user gesture Chromium playback ended','repeat','pause','guided mode','draft reload','Check source reveal','new attempt hides original','delete attempt'],'page_errors':errors},indent=2))
    print('PASS cached real WAV actual Chromium playback + repeat/pause/guided/reload/Check')
    browser.close()
